"""Generates data/sample30.csv and tests/expected.h (known-correct answers).
Run from the project root:  python3 tools/make_expected.py
Needs: numpy pandas statsmodels scipy"""
import numpy as np, pandas as pd, statsmodels.api as sm
from scipy import stats

rng = np.random.default_rng(424)
n = 30
educ = rng.integers(8, 19, n)
exper = rng.integers(0, 26, n)
female = rng.integers(0, 2, n)
lwage = (1.2 + 0.07*educ + 0.04*exper - 0.0007*exper**2 - 0.15*female
         + rng.normal(0, 0.25, n)).round(3)
highwage = (lwage > np.median(lwage)).astype(int)
pd.DataFrame(dict(educ=educ, exper=exper, female=female,
                  lwage=lwage, highwage=highwage)).to_csv("data/sample30.csv", index=False)

d = pd.read_csv("data/sample30.csv")
out = []
def put(name, v): out.append(f"#define {name} {float(v):.12g}")

def fit(y, cols):
    X = sm.add_constant(np.column_stack(cols))
    return sm.OLS(y, X).fit(), X

y = d.lwage.values; e = d.educ.values.astype(float); x = d.exper.values.astype(float)
# stage 1
put("E_MEAN_EDUC", e.mean()); put("E_VAR_EDUC", e.var(ddof=1)); put("E_SD_EDUC", e.std(ddof=1))
put("E_COV_EDUC_LWAGE", np.cov(e, y)[0, 1]); put("E_COR_EDUC_LWAGE", np.corrcoef(e, y)[0, 1])
m1, X1 = fit(y, [e])
put("E1_B0", m1.params[0]); put("E1_B1", m1.params[1])
put("E1_SST", m1.centered_tss); put("E1_SSE", m1.ess); put("E1_SSR", m1.ssr)
put("E1_R2", m1.rsquared); put("E1_SIGMA", np.sqrt(m1.scale))
put("E1_SE0", m1.bse[0]); put("E1_SE1", m1.bse[1])
put("E1_T0", m1.tvalues[0]); put("E1_T1", m1.tvalues[1])
put("E1_P0", m1.pvalues[0]); put("E1_P1", m1.pvalues[1])
ci = m1.conf_int(0.05); put("E1_CI1_LO", ci[1][0]); put("E1_CI1_HI", ci[1][1])
# stage 3: multiple regression
m2, X2 = fit(y, [e, x])
for i in range(3):
    put(f"E2_B{i}", m2.params[i]); put(f"E2_SE{i}", m2.bse[i])
    put(f"E2_T{i}", m2.tvalues[i]); put(f"E2_P{i}", m2.pvalues[i])
put("E2_R2", m2.rsquared); put("E2_ADJR2", m2.rsquared_adj); put("E2_SIGMA", np.sqrt(m2.scale))
put("E2_SSR", m2.ssr); put("E2_F", m2.fvalue); put("E2_FP", m2.f_pvalue)
# prediction at educ=12, exper=10
x0 = np.array([1, 12, 10.0]); XtXi = np.linalg.inv(X2.T @ X2)
sem = np.sqrt(m2.scale * x0 @ XtXi @ x0); fitv = x0 @ m2.params
tc = stats.t.ppf(0.975, m2.df_resid); sep = np.sqrt(sem**2 + m2.scale)
put("EP_FIT", fitv); put("EP_SEMEAN", sem)
put("EP_CI_LO", fitv - tc*sem); put("EP_CI_HI", fitv + tc*sem)
put("EP_PI_LO", fitv - tc*sep); put("EP_PI_HI", fitv + tc*sep)
put("E_TCRIT_DF27", stats.t.ppf(0.975, 27))
# quadratic
xsq = x**2
m3, X3 = fit(y, [e, x, xsq])
for i in range(4): put(f"E3_B{i}", m3.params[i])
put("E3_SSR", m3.ssr); put("E3_DF", m3.df_resid)
tp = -m3.params[2]/(2*m3.params[3]); put("E3_TURN", tp)
put("E3_ME10", m3.params[2] + 2*m3.params[3]*10); put("E3_ABOVE", (x > tp).sum())
# joint F: exper & exper^2 = 0 (restricted = lwage ~ educ)
q = 2; F = ((m1.ssr - m3.ssr)/q)/(m3.ssr/m3.df_resid)
put("E3_JF", F); put("E3_JFP", stats.f.sf(F, q, m3.df_resid))
# interaction + recentering
ee = e*x
m4, X4 = fit(y, [e, x, ee])
put("E4_B_EDUC", m4.params[1]); put("E4_B_INT", m4.params[3])
put("E4_EFFECT10", m4.params[1] + 10*m4.params[3])
m4r, _ = fit(y, [e, x, e*(x-10)])
put("E4R_THETA", m4r.params[1]); put("E4R_SE", m4r.bse[1])
cir = m4r.conf_int(0.05); put("E4R_CI_LO", cir[1][0]); put("E4R_CI_HI", cir[1][1])
put("E4R_DF", m4r.df_resid)
# standardized betas
z = lambda v: (v - v.mean())/v.std(ddof=1)
m5, _ = fit(z(y), [z(e), z(x)])
put("E5_ZB_EDUC", m5.params[1]); put("E5_ZB_EXPER", m5.params[2])
# chow test by female
ssr_p = m2.ssr; ssrs = []
for g in (0, 1):
    s = d[d.female == g]
    mg, _ = fit(s.lwage.values, [s.educ.values.astype(float), s.exper.values.astype(float)])
    ssrs.append(mg.ssr); put(f"E6_SSR_G{g}", mg.ssr); put(f"E6_N_G{g}", len(s))
k = 3; chow = ((ssr_p - sum(ssrs))/k)/(sum(ssrs)/(n - 2*k))
put("E6_SSR_POOLED", ssr_p); put("E6_CHOW_F", chow)
# LPM
hw = d.highwage.values.astype(float)
m7, _ = fit(hw, [e, x]); fv = m7.fittedvalues
put("E7_B0", m7.params[0]); put("E7_B1", m7.params[1]); put("E7_B2", m7.params[2])
put("E7_OUTSIDE", ((fv < 0) | (fv > 1)).sum())
# formulas
put("EF_F_RESTR", ((395269 - 394904)/3)/(394904/1685))
put("EF_ADJR2", 1 - (1 - 0.6724)*(88 - 1)/(88 - 4))
put("EF_PCT_009", 100*(np.exp(0.09) - 1)); put("EF_PCT_04", 100*(np.exp(0.4) - 1))
put("EF_CHOW", ((50.0 - (20.0 + 25.0))/3)/((20.0 + 25.0)/(40 - 6)))
# distribution spot checks
put("ED_P_T2095_DF931", 2*stats.t.sf(2.095, 931))
put("ED_P_T1_DF10", 2*stats.t.sf(1.0, 10))
put("ED_P_F0518", stats.f.sf(0.518, 3, 1685)); put("ED_P_F5_DF2_20", stats.f.sf(5.0, 2, 20))
put("ED_TCRIT_DF10", stats.t.ppf(0.975, 10)); put("ED_TCRIT_DF1688", stats.t.ppf(0.975, 1688))
open("tests/expected.h", "w").write("/* generated by tools/make_expected.py */\n" + "\n".join(out) + "\n")
print(len(out), "constants"); print(d.head(8).to_string()); print("outside [0,1]:", ((fv<0)|(fv>1)).sum(), " above turn:", (x>tp).sum(), "turn", tp)
